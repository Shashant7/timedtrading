// worker/stripe-vip-code.js
//
// 2026-07-27 — VIP promotion-code detection at checkout.
//
// Backstory: `POST /timed/admin/vip-code` mints a 100%-off Stripe coupon
// + single-use promotion_code and inserts (code, stripe_coupon_id,
// stripe_promo_id) into the `vip_codes` D1 table. The user pastes the
// code at checkout; Stripe applies the discount and creates a $0
// subscription; Stripe fires `checkout.session.completed`; the webhook
// used to unconditionally set tier='pro'.
//
// Silent bug (2026-07-27): the webhook never checked whether a VIP
// promotion_code was applied. A user redeeming a VIP invite ended up in
// Pro Trial and had to be flipped by hand. This module centralizes the
// "was a VIP promo code applied to this subscription?" decision so the
// webhook can grant tier='vip' + subscription_status='manual' (matching
// the admin-flip semantics, so a follow-on customer.subscription.deleted
// won't downgrade) and mark the `vip_codes` row as used_by_email.

/**
 * Extract candidate identifiers for the promotion_code applied to a
 * Stripe subscription. Stripe supports two shapes:
 *   - Legacy: `subscription.discount = { promotion_code: 'promo_xxx' | { id, code } }`
 *   - Newer:  `subscription.discounts = [{ promotion_code: 'promo_xxx' | { id, code } }]`
 *
 * Returns { promoId?, code? } — either field may be present. Empty
 * object when the subscription has no promotion code.
 */
export function extractSubscriptionPromoCode(subObj) {
  if (!subObj || typeof subObj !== "object") return {};
  const buckets = [];
  if (subObj.discount) buckets.push(subObj.discount);
  if (Array.isArray(subObj.discounts)) {
    for (const d of subObj.discounts) if (d) buckets.push(d);
  }
  for (const d of buckets) {
    const pc = d?.promotion_code;
    if (!pc) continue;
    if (typeof pc === "string") return { promoId: pc };
    if (typeof pc === "object") {
      const promoId = pc.id || null;
      const code = pc.code ? String(pc.code) : null;
      if (promoId || code) return { promoId, code };
    }
  }
  return {};
}

/**
 * Look up a VIP code row in D1 by stripe_promo_id OR (case-insensitive)
 * code. Returns the row or null. Best-effort: never throws.
 *
 * The lookup accepts either input because the webhook receives whichever
 * shape Stripe returned (id when unexpanded, both when expanded). The
 * code column is stored as-generated by Stripe (upper-case typically)
 * but users paste it case-sensitively — we do a case-insensitive match
 * to match Stripe's own applied-code behavior.
 */
export async function lookupVipCodeRow(env, { promoId = null, code = null } = {}) {
  const db = env?.DB;
  if (!db) return null;
  if (!promoId && !code) return null;
  try {
    if (promoId) {
      const byId = await db.prepare(
        `SELECT * FROM vip_codes WHERE stripe_promo_id = ?1 LIMIT 1`,
      ).bind(String(promoId)).first();
      if (byId) return byId;
    }
    if (code) {
      const byCode = await db.prepare(
        `SELECT * FROM vip_codes WHERE UPPER(code) = UPPER(?1) LIMIT 1`,
      ).bind(String(code)).first();
      if (byCode) return byCode;
    }
  } catch (e) {
    console.warn("[VIP_CODE] lookup failed:", String(e?.message || e).slice(0, 160));
  }
  return null;
}

/**
 * Compose the tier grant that should apply to the checkout completion.
 *
 * When a VIP promotion_code was applied → return tier='vip' + 'manual'
 * so this account is treated like an admin flip (permanent grant, not
 * subject to Stripe subscription lifecycle). Otherwise fall through to
 * the Pro grant already used by the checkout handler.
 *
 * Pure function — takes the subscription + a lookup callback (so it's
 * trivially testable without a real D1 handle).
 *
 * @param {object} args
 * @param {object} args.subObj                Stripe subscription object
 * @param {(query: {promoId?:string, code?:string}) => Promise<object|null>} args.lookup
 *   Async lookup for a VIP code row.
 * @returns {Promise<{ tier: 'pro'|'vip', subscription_status: string,
 *   vip_code_row: object|null, promo: {promoId?:string, code?:string} }>}
 */
export async function resolveCheckoutTierGrant({ subObj, lookup } = {}) {
  const promo = extractSubscriptionPromoCode(subObj);
  if (!promo.promoId && !promo.code) {
    return { tier: "pro", subscription_status: "active_or_trialing", vip_code_row: null, promo: {} };
  }
  const vipRow = typeof lookup === "function" ? await lookup(promo) : null;
  if (!vipRow) {
    return { tier: "pro", subscription_status: "active_or_trialing", vip_code_row: null, promo };
  }
  return { tier: "vip", subscription_status: "manual", vip_code_row: vipRow, promo };
}
